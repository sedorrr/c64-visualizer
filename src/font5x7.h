/* Narrow 3-column variants so that more words fit on a 32-wide panel. */
static const uint8_t FONT_NARROW_a[3] = {0x20,0x54,0x7C};
static const uint8_t FONT_NARROW_n[3] = {0x7C,0x04,0x78};
static const uint8_t FONT_NARROW_t[3] = {0x08,0x3E,0x48};
static const uint8_t FONT_NARROW_u[3] = {0x3C,0x40,0x7C};

/* Proportional lookup: returns the glyph columns and sets *w to its width (3 or 5). */
static inline const uint8_t *font_glyph_w(char c, int *w) {
    *w = 3;
    switch (c) {
        case 'a': return FONT_NARROW_a;
        case 'n': return FONT_NARROW_n;
        case 't': return FONT_NARROW_t;
        case 'u': return FONT_NARROW_u;
        default: break;
    }
    *w = 5;
    if (c == ' ') { *w = 3; return FONT_SPACE; }
    if (c >= '0' && c <= '9') return FONT_DIGITS[c - '0'];
    if (c >= 'A' && c <= 'Z') return FONT_UPPER[c - 'A'];
    if (c >= 'a' && c <= 'z') return FONT_LOWER[c - 'a'];
    if (c == '!') { *w = 1; return FONT_EXCL + 2; }
    if (c == '.') { *w = 2; return FONT_DOT + 1; }
    if (c == '-') { *w = 3; return FONT_MINUS; }
    if (c == ':') { *w = 2; return FONT_COLON + 1; }
    if (c == ',') { *w = 2; return FONT_COMMA + 1; }
    if (c == '\'') { *w = 1; return FONT_APOS + 2; }
    if (c == '"') { *w = 3; return FONT_QUOTE + 1; }
    if (c == '(') { *w = 3; return FONT_LPAR + 1; }
    if (c == ')') { *w = 3; return FONT_RPAR + 1; }
    if (c == '?') return FONT_QUEST;
    if (c == '/') return FONT_SLASH;
    if (c == '&') return FONT_AMP;
    if (c == '+') return FONT_PLUS;
    if (c == '#') return FONT_HASH;
    if (c == '%') return FONT_PCT;
    return FONT_UNKNOWN;
}

static inline const uint8_t *font_glyph(char c) {
    if (c >= '0' && c <= '9') return FONT_DIGITS[c - '0'];
    if (c >= 'A' && c <= 'Z') return FONT_UPPER[c - 'A'];
    if (c >= 'a' && c <= 'z') return FONT_LOWER[c - 'a'];
    if (c == ' ') return FONT_SPACE;
    if (c == '!') return FONT_EXCL;
    if (c == '.') return FONT_DOT;
    if (c == '-') return FONT_MINUS;
    if (c == ':') return FONT_COLON;
    if (c == ',') return FONT_COMMA;
    if (c == '?') return FONT_QUEST;
    if (c == '\'') return FONT_APOS;
    if (c == '"') return FONT_QUOTE;
    if (c == '/') return FONT_SLASH;
    if (c == '&') return FONT_AMP;
    if (c == '(') return FONT_LPAR;
    if (c == ')') return FONT_RPAR;
    if (c == '+') return FONT_PLUS;
    if (c == '#') return FONT_HASH;
    if (c == '%') return FONT_PCT;
    return FONT_UNKNOWN;
}
