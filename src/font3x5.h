/* Tiny 3x5 font (uppercase, digits, a few symbols) for the sine scroller. Column-major, bit 0 = top. */
#pragma once
#include <stdint.h>

static const uint8_t TINY_AZ[26][3] = {
    {0x1E,0x05,0x1E},
    {0x1F,0x15,0x0A},
    {0x0E,0x11,0x11},
    {0x1F,0x11,0x0E},
    {0x1F,0x15,0x11},
    {0x1F,0x05,0x01},
    {0x0E,0x11,0x1D},
    {0x1F,0x04,0x1F},
    {0x11,0x1F,0x11},
    {0x08,0x10,0x0F},
    {0x1F,0x04,0x1B},
    {0x1F,0x10,0x10},
    {0x1F,0x06,0x1F},
    {0x1F,0x01,0x1E},
    {0x0E,0x11,0x0E},
    {0x1F,0x05,0x02},
    {0x0E,0x19,0x16},
    {0x1F,0x05,0x1A},
    {0x12,0x15,0x09},
    {0x01,0x1F,0x01},
    {0x1F,0x10,0x1F},
    {0x0F,0x10,0x0F},
    {0x1F,0x0C,0x1F},
    {0x1B,0x04,0x1B},
    {0x03,0x1C,0x03},
    {0x19,0x15,0x13}};
static const uint8_t TINY_09[10][3] = {
    {0x1F,0x11,0x1F},
    {0x12,0x1F,0x10},
    {0x19,0x15,0x12},
    {0x11,0x15,0x0A},
    {0x07,0x04,0x1F},
    {0x17,0x15,0x09},
    {0x1E,0x15,0x1D},
    {0x01,0x1D,0x03},
    {0x1F,0x15,0x1F},
    {0x17,0x15,0x0F}};
static const uint8_t TINY_MINUS[3] = {0x04,0x04,0x04};
static const uint8_t TINY_QUEST[3] = {0x01,0x15,0x02};
static const uint8_t TINY_EXCL[1] = {0x17};
static const uint8_t TINY_DOT[1] = {0x10};
static const uint8_t TINY_COLON[1] = {0x0A};
static const uint8_t TINY_SPACE[2] = {0, 0};

/* glyph columns for c, *w = width (1..3); lowercase is shown as uppercase */
static inline const uint8_t *tiny_glyph(char c, int *w) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    *w = 3;
    if (c >= 'A' && c <= 'Z') return TINY_AZ[c - 'A'];
    if (c >= '0' && c <= '9') return TINY_09[c - '0'];
    if (c == '-') return TINY_MINUS;
    if (c == '?') return TINY_QUEST;
    *w = 1;
    if (c == '!') return TINY_EXCL;
    if (c == '.') return TINY_DOT;
    if (c == ':') return TINY_COLON;
    *w = 2;
    return TINY_SPACE;
}

/* column col (0..2) of character c in a fixed 3-column cell; narrow glyphs are centred */
static inline uint8_t font3x5_col(char c, int col) {
    int w;
    const uint8_t *g = tiny_glyph(c, &w);
    if (w == 3) return g[col];
    if (w == 1) return col == 1 ? g[0] : 0;
    return 0;
}
